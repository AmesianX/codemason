/// CODEMASON_SPINNER_VERBS=word1,word2 replaces the pool; else default.
pub fn get_spinner_verbs() -> Vec<String> {
    if let Ok(override_val) = std::env::var("CODEMASON_SPINNER_VERBS") {
        let custom: Vec<String> = override_val
            .split(',')
            .map(|w| w.trim().to_string())
            .filter(|w| !w.is_empty())
            .collect();
        if !custom.is_empty() {
            return custom;
        }
    }
    SPINNER_VERBS.iter().map(|s| s.to_string()).collect()
}

